// App setup: applies the app name (Arabic / English) and the launcher icon
// from app_setup.json to every platform.
//
//   dart run tool/setup_app.dart            (uses app_setup.json)
//   dart run tool/setup_app.dart other.json (uses another setup file)
//
// app_setup.json:
//   {
//     "nameAr": "...",              shown when the phone is in Arabic
//     "nameEn": "...",              shown when the phone is in English (and the default)
//     "icon": "assets/images/logo.png",  square PNG, 1024x1024 or larger
//     "iconBackground": "#FFFFFF"   optional, Android adaptive icon background
//   }
//
// Run it again whenever the setup file or the image changes, then rebuild the app.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) async {
  final setupPath = args.isNotEmpty ? args.first : 'app_setup.json';
  final setupFile = File(setupPath);
  if (!setupFile.existsSync()) {
    _fail('Setup file not found: $setupPath');
  }

  final Map<String, dynamic> setup;
  try {
    setup = jsonDecode(setupFile.readAsStringSync()) as Map<String, dynamic>;
  } catch (e) {
    _fail('$setupPath is not valid JSON: $e');
  }

  final nameAr = (setup['nameAr'] as String?)?.trim() ?? '';
  final nameEn = (setup['nameEn'] as String?)?.trim() ?? '';
  final icon = (setup['icon'] as String?)?.trim() ?? '';
  final iconBackground =
      (setup['iconBackground'] as String?)?.trim() ?? '#FFFFFF';

  if (nameAr.isEmpty) _fail('"nameAr" is missing in $setupPath');
  if (nameEn.isEmpty) _fail('"nameEn" is missing in $setupPath');
  if (icon.isEmpty) _fail('"icon" is missing in $setupPath');
  if (!File(icon).existsSync()) _fail('Icon image not found: $icon');
  if (!icon.toLowerCase().endsWith('.png')) {
    _fail('The icon must be a PNG image: $icon');
  }

  print('App setup: "$nameEn" / "$nameAr", icon $icon');

  _writeDartAppInfo(nameAr, nameEn);
  _setupAndroid(nameAr, nameEn);
  _setupIos(nameAr, nameEn);
  _setupWindows(nameEn);
  await _generateIcons(icon, iconBackground);
  // After the icons: the icon tool rewrites web/manifest.json
  _setupWeb(nameEn);

  print('\nDone. Rebuild the app (flutter clean is not needed).');
}

// ---------------------------------------------------------------- Dart

void _writeDartAppInfo(String nameAr, String nameEn) {
  _write('lib/core/app_info.dart', '''
// GENERATED by tool/setup_app.dart from app_setup.json. Do not edit by hand:
// change app_setup.json and run `dart run tool/setup_app.dart`.

/// The app name, in Arabic and English.
class AppInfo {
  static const nameAr = ${_dartString(nameAr)};
  static const nameEn = ${_dartString(nameEn)};

  /// The name in the given language code ('ar' or 'en').
  static String name(String languageCode) =>
      languageCode == 'en' ? nameEn : nameAr;
}
''');
}

// ---------------------------------------------------------------- Android

void _setupAndroid(String nameAr, String nameEn) {
  const res = 'android/app/src/main/res';
  _write('$res/values/strings.xml', _androidStrings(nameEn));
  _write('$res/values-ar/strings.xml', _androidStrings(nameAr));

  const manifestPath = 'android/app/src/main/AndroidManifest.xml';
  final manifest = File(manifestPath).readAsStringSync();
  final updated = manifest.replaceFirst(
      RegExp(r'android:label="[^"]*"'), 'android:label="@string/app_name"');
  if (updated != manifest) _write(manifestPath, updated);
}

String _androidStrings(String name) => '''
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/setup_app.dart from app_setup.json -->
<resources>
    <string name="app_name">${_androidEscape(name)}</string>
</resources>
''';

// ---------------------------------------------------------------- iOS

// Fixed ids so running the setup again never adds duplicates.
const _idBuildFile = '5E7A00000000000000000001';
const _idVariant = '5E7A00000000000000000002';
const _idEn = '5E7A00000000000000000003';
const _idAr = '5E7A00000000000000000004';

void _setupIos(String nameAr, String nameEn) {
  // Localized home-screen name
  _write('ios/Runner/en.lproj/InfoPlist.strings', _iosStrings(nameEn));
  _write('ios/Runner/ar.lproj/InfoPlist.strings', _iosStrings(nameAr));

  // Default name + the languages the app supports
  const plistPath = 'ios/Runner/Info.plist';
  var plist = File(plistPath).readAsStringSync();
  plist = plist.replaceFirstMapped(
      RegExp(r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)'),
      (m) => '${m[1]}${_xmlEscape(nameEn)}${m[2]}');
  if (!plist.contains('<key>CFBundleLocalizations</key>')) {
    plist = plist.replaceFirst(
        '<key>CFBundleDisplayName</key>',
        '<key>CFBundleLocalizations</key>\n\t<array>\n\t\t<string>ar</string>\n'
            '\t\t<string>en</string>\n\t</array>\n\t<key>CFBundleDisplayName</key>');
  }
  _write(plistPath, plist);

  // Add InfoPlist.strings to the Xcode project (once)
  const pbxPath = 'ios/Runner.xcodeproj/project.pbxproj';
  var pbx = File(pbxPath).readAsStringSync();
  if (!pbx.contains(_idVariant)) {
    pbx = _insertBefore(pbx, '/* End PBXBuildFile section */',
        '\t\t$_idBuildFile /* InfoPlist.strings in Resources */ = {isa = PBXBuildFile; fileRef = $_idVariant /* InfoPlist.strings */; };\n');
    pbx = _insertBefore(pbx, '/* End PBXFileReference section */',
        '\t\t$_idEn /* en */ = {isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = en; path = en.lproj/InfoPlist.strings; sourceTree = "<group>"; };\n'
        '\t\t$_idAr /* ar */ = {isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = ar; path = ar.lproj/InfoPlist.strings; sourceTree = "<group>"; };\n');
    pbx = _insertBefore(pbx, '/* End PBXVariantGroup section */',
        '\t\t$_idVariant /* InfoPlist.strings */ = {\n'
        '\t\t\tisa = PBXVariantGroup;\n'
        '\t\t\tchildren = (\n'
        '\t\t\t\t$_idEn /* en */,\n'
        '\t\t\t\t$_idAr /* ar */,\n'
        '\t\t\t);\n'
        '\t\t\tname = InfoPlist.strings;\n'
        '\t\t\tsourceTree = "<group>";\n'
        '\t\t};\n');
    // Runner group (next to Info.plist) and the Resources build phase
    pbx = _insertAfterLine(pbx, '97C147021CF9000F007C117D /* Info.plist */,',
        '\t\t\t\t$_idVariant /* InfoPlist.strings */,');
    pbx = _insertAfterLine(pbx, '/* Main.storyboard in Resources */,',
        '\t\t\t\t$_idBuildFile /* InfoPlist.strings in Resources */,');
  }
  if (!RegExp(r'knownRegions = \([^)]*\bar,', multiLine: true).hasMatch(pbx)) {
    pbx = pbx.replaceFirst(
        RegExp(r'knownRegions = \(\s*\n'), 'knownRegions = (\n\t\t\t\tar,\n');
  }
  _write(pbxPath, pbx);
}

String _iosStrings(String name) => '''
/* GENERATED by tool/setup_app.dart from app_setup.json */
"CFBundleDisplayName" = "${_quoteEscape(name)}";
"CFBundleName" = "${_quoteEscape(name)}";
''';

// ---------------------------------------------------------------- Web

void _setupWeb(String nameEn) {
  const manifestPath = 'web/manifest.json';
  if (File(manifestPath).existsSync()) {
    final manifest = jsonDecode(File(manifestPath).readAsStringSync())
        as Map<String, dynamic>;
    manifest['name'] = nameEn;
    manifest['short_name'] = nameEn;
    _write(manifestPath,
        '${const JsonEncoder.withIndent('    ').convert(manifest)}\n');
  }

  const indexPath = 'web/index.html';
  if (File(indexPath).existsSync()) {
    var html = File(indexPath).readAsStringSync();
    html = html
        .replaceFirst(RegExp(r'<title>[^<]*</title>'),
            '<title>${_xmlEscape(nameEn)}</title>')
        .replaceFirst(
            RegExp(r'(name="apple-mobile-web-app-title" content=")[^"]*'),
            'name="apple-mobile-web-app-title" content="${_xmlEscape(nameEn)}');
    _write(indexPath, html);
  }
}

// ---------------------------------------------------------------- Windows

void _setupWindows(String nameEn) {
  const mainPath = 'windows/runner/main.cpp';
  if (File(mainPath).existsSync()) {
    final cpp = File(mainPath).readAsStringSync();
    _write(
        mainPath,
        cpp.replaceFirstMapped(RegExp(r'window\.Create\(L"[^"]*"'),
            (_) => 'window.Create(L"${_quoteEscape(nameEn)}"'));
  }
  const rcPath = 'windows/runner/Runner.rc';
  if (File(rcPath).existsSync()) {
    var rc = File(rcPath).readAsStringSync();
    for (final key in ['FileDescription', 'ProductName']) {
      rc = rc.replaceFirstMapped(RegExp('(VALUE "$key", )"[^"]*"'),
          (m) => '${m[1]}"${_quoteEscape(nameEn)}"');
    }
    _write(rcPath, rc);
  }
}

// ---------------------------------------------------------------- Icons

Future<void> _generateIcons(String icon, String background) async {
  _write('flutter_launcher_icons.yaml', '''
# GENERATED by tool/setup_app.dart from app_setup.json
flutter_launcher_icons:
  image_path: "$icon"
  android: "ic_launcher"
  adaptive_icon_background: "$background"
  adaptive_icon_foreground: "$icon"
  ios: true
  remove_alpha_ios: true
  background_color_ios: "$background"
  web:
    generate: true
    image_path: "$icon"
  windows:
    generate: true
    image_path: "$icon"
    icon_size: 256
''');

  print('Generating launcher icons...');
  final result = await Process.run(
    Platform.resolvedExecutable,
    ['run', 'flutter_launcher_icons', '-f', 'flutter_launcher_icons.yaml'],
    runInShell: true,
  );
  stdout.write(result.stdout);
  stderr.write(result.stderr);
  if (result.exitCode != 0) {
    _fail('Icon generation failed (run `flutter pub get` first).');
  }

  // flutter_launcher_icons wrongly sets this Xcode setting to the icon name;
  // it is a YES/NO setting.
  const pbxPath = 'ios/Runner.xcodeproj/project.pbxproj';
  final pbx = File(pbxPath).readAsStringSync();
  _write(
      pbxPath,
      pbx.replaceAll(
          RegExp(r'ASSETCATALOG_COMPILER_GENERATE_SWIFT_ASSET_SYMBOL_EXTENSIONS = (?!YES;|NO;)[^;]*;'),
          'ASSETCATALOG_COMPILER_GENERATE_SWIFT_ASSET_SYMBOL_EXTENSIONS = YES;'));
}

// ---------------------------------------------------------------- Helpers

void _write(String path, String content) {
  final file = File(path);
  file.parent.createSync(recursive: true);
  if (file.existsSync() && file.readAsStringSync() == content) return;
  file.writeAsStringSync(content);
  print('  updated $path');
}

String _insertBefore(String text, String marker, String insert) {
  final i = text.indexOf(marker);
  if (i < 0) _fail('Unexpected Xcode project format (missing "$marker")');
  return text.replaceRange(i, i, insert);
}

String _insertAfterLine(String text, String lineContains, String newLine) {
  final i = text.indexOf(lineContains);
  if (i < 0) _fail('Unexpected Xcode project format (missing "$lineContains")');
  final end = text.indexOf('\n', i);
  return text.replaceRange(end, end, '\n$newLine');
}

String _dartString(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

String _xmlEscape(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

String _androidEscape(String s) =>
    _xmlEscape(s).replaceAll("'", r"\'").replaceAll('@', r'\@');

String _quoteEscape(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll('"', r'\"');

Never _fail(String message) {
  stderr.writeln('ERROR: $message');
  exit(1);
}
